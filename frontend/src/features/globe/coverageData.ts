// Контуры 37 HiRISE DTM и маркеры районов из реестра продуктов (кандидатные границы съёмки, не проходимые площадки).
export interface DtmFootprint {
  id: string;
  region: string;
  ring: [number, number][];
}

import { pick } from '@/shared/i18n/lang';

export interface RegionMarker {
  slug: string;
  /** Подпись на текущем языке: шар читает её, когда строит метки. */
  readonly name: string;
  nameRu: string;
  nameEn: string;
  mission: string;
  lat: number;
  lon: number;
}

function region(slug: string, nameRu: string, nameEn: string, mission: string, lat: number, lon: number): RegionMarker {
  return {
    slug,
    nameRu,
    nameEn,
    mission,
    lat,
    lon,
    get name() {
      return pick(nameRu, nameEn);
    },
  };
}

