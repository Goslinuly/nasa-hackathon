// Когда перерисовывать карту теней прогулки. Раньше она рисовалась каждый кадр, то есть весь
// ближний рельеф шёл в кадр дважды. Пешеход проходит меньше метра в секунду, солнце смещается
// на доли градуса в минуту — перерисовка нужна, только когда картинка заметно изменилась.
// Матрица теней three.js считается в момент отрисовки карты, поэтому между перерисовками
// тени остаются согласованными с картой, просто «привязаны» к последнему положению.

/** Пешком: сдвиг, после которого тени перерисовываются, м. */
export const SHADOW_MOVE_WALK_M = 1.5;
/** На ровере модель отбрасывает тень и едет вместе с камерой: обновляем при любом движении. */
export const SHADOW_MOVE_ROVER_M = 0.05;
/** Поворот солнца, после которого тени перерисовываются, градусы. */
export const SHADOW_SUN_DEG = 0.2;
/** Страховка: не реже раза в столько секунд (смена детализации рельефа и т.п.). */
export const SHADOW_MAX_AGE_S = 2;

const SUN_COS = Math.cos((SHADOW_SUN_DEG * Math.PI) / 180);

export interface ShadowCheck {
  /** Сдвиг игрока с последней перерисовки, м. */
  movedM: number;
  /** Скалярное произведение единичных направлений на солнце сейчас и при перерисовке. */
  sunDot: number;
  /** Секунд с последней перерисовки. */
  ageS: number;
  vehicle: 'rover' | 'walk';
}

export function shadowNeedsRefresh(c: ShadowCheck): boolean {
  const moveLimit = c.vehicle === 'rover' ? SHADOW_MOVE_ROVER_M : SHADOW_MOVE_WALK_M;
  return c.movedM >= moveLimit || c.sunDot < SUN_COS || c.ageS >= SHADOW_MAX_AGE_S;
}
